# ------------------------------------------------------------------ sitemap
def build_sitemap(lastmod):
    pairs = [("", "zh/")] + [("services/%s/" % s["slug"], "zh/services/%s/" % s["slug"]) for s in SERVICES] + [("faq/", "zh/faq/")]
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for en, zh in pairs:
        for loc in (en, zh):
            out += ["  <url>", "    <loc>%s%s</loc>" % (SITE, loc), "    <lastmod>%s</lastmod>" % lastmod,
                    '    <xhtml:link rel="alternate" hreflang="en" href="%s%s"/>' % (SITE, en),
                    '    <xhtml:link rel="alternate" hreflang="zh-Hans" href="%s%s"/>' % (SITE, zh),
                    '    <xhtml:link rel="alternate" hreflang="x-default" href="%s%s"/>' % (SITE, en),
                    "  </url>"]
    out.append("</urlset>\n")
    write("sitemap.xml", "\n".join(out))


