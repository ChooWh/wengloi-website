def build_zh_home(zh):
    s = read("index.html")
    t = zh["strings"]
    used = set()

    def fill(m):
        key = m.group(3)
        if key not in t:
            raise SystemExit("no Chinese text for key " + key)
        used.add(key)
        return "<%s%s>%s</%s>" % (m.group(1), m.group(2), t[key], m.group(1))

    # Elements carrying data-i18n: replace their inner HTML.
    s = re.sub(r'<(\w+)(\s[^>]*?data-i18n="([^"]+)"[^>]*)>(.*?)</\1>', fill, s, flags=re.S)

    def attr(name, src):
        def f(m):
            tag, key = m.group(0), m.group(1)
            used.add(key)
            return re.sub(r'(?<![-\w])%s="[^"]*"' % src, '%s="%s"' % (src, t[key].replace('"', "&quot;")), tag)
        return f
    s = re.sub(r'<[^>]*\bdata-i18n-alt="([^"]+)"[^>]*>', attr("alt", "alt"), s)
    s = re.sub(r'<[^>]*\bdata-i18n-cap="([^"]+)"[^>]*>', attr("cap", "data-cap"), s)

    # Language, title, description, social tags, canonical, hreflang.
    s = sub1(r'<html lang="en">', '<html lang="zh-Hans">', s)
    s = sub1(r"<title>.*?</title>", "<title>%s</title>" % t["meta.title"], s)
    s = sub1(r'<meta name="description" content="[^"]*">',
             '<meta name="description" content="%s">' % t["meta.desc"], s)
    s = sub1(r'<meta property="og:title" content="[^"]*">',
             '<meta property="og:title" content="%s">' % t["meta.title"], s)
    s = sub1(r'<meta property="og:description" content="[^"]*">',
             '<meta property="og:description" content="%s">' % t["meta.desc"], s)
    s = sub1(r'<meta property="og:url" content="[^"]*">',
             '<meta property="og:url" content="%szh/">' % SITE, s)
    s = sub1(r'<meta property="og:locale" content="en_MY">\n<meta property="og:locale:alternate" content="zh_CN">',
             '<meta property="og:locale" content="zh_CN">\n<meta property="og:locale:alternate" content="en_MY">', s)
    s = sub1(r'<link rel="canonical" href="[^"]*">', '<link rel="canonical" href="%szh/">' % SITE, s)
    s = sub1(r'<script id="lang-redirect">.*?</script>\n', "", s, flags=re.S)
    s = sub1(r'(<link href="https://fonts.googleapis.com/css2\?family=Montserrat[^>]*>)',
             r'\1\n<link href="https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;700;900&display=swap" rel="stylesheet">', s)

    # Language switch: links, Chinese marked current.
    s = sub1(r'<div class="lang".*?</div>',
             '<div class="lang" role="group" aria-label="Language / 语言"><a href="../" data-lang="en" hreflang="en" lang="en">EN</a>'
             '<a href="./" data-lang="zh" hreflang="zh-Hans" lang="zh-Hans" aria-current="true">中文</a></div>', s, flags=re.S)

    # Marquee and WhatsApp prefilled text.
    marq = "".join("<span>%s <i>•</i></span>" % w for w in zh["marquee"])
    s = sub1(r'(<div class="track" id="mtrack">\s*).*?(\s*</div>)', lambda m: m.group(1) + marq + m.group(2), s, flags=re.S)
    s = s.replace("text=" + urllib.parse.quote(WA_EN), "text=" + urllib.parse.quote(zh["wa_text"]))

    # Paths: the page lives one folder down.
    s = re.sub(r'''(["'(])assets/''', r"\1../assets/", s)

    s = s.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by tools/build.py from index.html and tools/zh.json. Do not edit by hand. -->", 1)
    missing = set(re.findall(r'data-i18n(?:-alt|-cap)?="([^"]+)"', read("index.html"))) - used
    if missing:
        raise SystemExit("keys not translated: %s" % sorted(missing))
    write("zh/index.html", s)


